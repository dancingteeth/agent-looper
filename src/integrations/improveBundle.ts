/**
 * Turn a parsed shadcn/improve plan into an Agent Looper bundle:
 *
 * | Plan                                   | Bundle                                      |
 * | -------------------------------------- | ------------------------------------------- |
 * | Done criteria with commands            | `verify.sh` checks (exit 0 / no output)     |
 * | "No files outside the in-scope list"   | `verify.sh` scope check vs. the run baseline |
 * | Done criteria without commands         | judge-checked criteria → `reviewGate: true` |
 * | STOP conditions                        | worker writes `STOP.md` → verify exit 75 (parked) |
 * | Planned at `<sha>` + drift check       | `setup.sh` parks the loop if in-scope files drifted |
 * | Commands table → Install               | `setup.sh` bootstrap                         |
 * | Effort S / M / L                       | `maxIterations` 4 / 6 / 10                   |
 * | `plans/README.md` order + Depends on   | `loop-batch.json` (batch stops at first failure) |
 *
 * Pure: returns file contents; the CLI writes them.
 */
import type { ImprovePlan, PlanCheck, PlanCriterion, PlanIndexRow } from './improvePlan.js'

export const IMPROVE_STATE_DIR = 'agent-loop-import'
export const IMPROVE_STOP_FILE = 'STOP.md'
export const IMPROVE_BATCH_DIR = 'improve-batch'

export type ImproveBundle = {
  name: string
  files: Record<'GOAL.md' | 'verify.sh' | 'setup.sh' | 'loop.json', string>
  checks: PlanCheck[]
  checksFrom: 'done-criteria' | 'step-verify'
  scopeCheck: boolean
  driftCheck: boolean
  judgeCriteria: string[]
  reviewGate: boolean
  maxIterations: number
  warnings: string[]
}

export type BuildImproveBundleOptions = {
  /** Loop dir relative to the repo root, forward slashes (e.g. `.cursor/loops/improve-001-x`). */
  loopRel: string
  /** Plan file relative to the repo root, for provenance. */
  planRel: string
}

const EFFORT_ITERATIONS: Record<string, number> = { S: 4, M: 6, L: 10 }
const DEFAULT_ITERATIONS = 6

const SAFE_SCOPE_PATH = /^[\w./*@+-]+$/
const SAFE_INSTALL =
  /^(pnpm|npm|yarn|bun|uv|poetry|pip|pip3|bundle|cargo|go|mix|dotnet|composer)(\s+[\w:@./=-]+)*$/

export function shq(s: string): string {
  return `'${s.replace(/'/g, `'\\''`)}'`
}

export function improveLoopName(plan: Pick<ImprovePlan, 'number' | 'slug'>): string {
  return `improve-${plan.number}-${plan.slug}`.slice(0, 64).replace(/-+$/, '')
}

function effortIterations(effort: string | undefined): number {
  const key = (effort ?? '').trim().toUpperCase().charAt(0)
  return EFFORT_ITERATIONS[key] ?? DEFAULT_ITERATIONS
}

function dedupeChecks(checks: PlanCheck[]): PlanCheck[] {
  const seen = new Set<string>()
  return checks.filter((c) => {
    const key = `${c.expect}\0${c.command}`
    if (seen.has(key)) return false
    seen.add(key)
    return true
  })
}

/** Judge-only: a done criterion with no runnable command (and not scope / index bookkeeping). */
function judgeCriteria(criteria: PlanCriterion[]): string[] {
  return criteria
    .filter((c) => !c.indexBookkeeping && !c.scopeCheck && c.checks.length === 0)
    .map((c) => c.text)
}

/** Drop the plan's own H1 and demote the rest one level (they sit under `## Plan`). Fences untouched. */
function demotePlanBody(body: string): string {
  let inFence = false
  const out: string[] = []
  for (const line of body.split('\n')) {
    if (/^\s*(```|~~~)/.test(line)) inFence = !inFence
    if (!inFence && /^#\s/.test(line)) continue
    if (!inFence && /^#{2,5}\s/.test(line)) {
      out.push(`#${line}`)
      continue
    }
    out.push(line)
  }
  return out.join('\n').replace(/^\n+/, '').trimEnd()
}

function scopePatterns(inScope: string[], warnings: string[]): string[] {
  const patterns: string[] = []
  for (const p of inScope) {
    if (!SAFE_SCOPE_PATH.test(p)) {
      warnings.push(`in-scope path \`${p}\` has unusual characters — left out of the scope check`)
      continue
    }
    if (p.endsWith('/')) patterns.push(`${shq(p)}*`)
    else if (p.includes('*')) patterns.push(p)
    else patterns.push(shq(p))
  }
  return patterns
}

function bashPreamble(loopRel: string, name: string): string[] {
  return [
    'REPO_ROOT="$(git rev-parse --show-toplevel 2>/dev/null || pwd)"',
    'cd "$REPO_ROOT"',
    `LOOP_DIR=${shq(loopRel)}`,
    `STATE_DIR="$(git rev-parse --git-path ${shq(`${IMPROVE_STATE_DIR}/${name}`)})"`,
  ]
}

function renderVerify(
  plan: ImprovePlan,
  name: string,
  opts: BuildImproveBundleOptions,
  checks: PlanCheck[],
  scope: string[] | undefined,
): string {
  const lines = [
    '#!/usr/bin/env bash',
    `# Generated by agent-loop-import from ${opts.planRel} (shadcn/improve plan ${plan.number}).`,
    '# Checks come from the plan\'s "Done criteria". Review before the first run;',
    '# fix the plan and re-import (--force) rather than hand-editing.',
    'set -uo pipefail',
    '',
    ...bashPreamble(opts.loopRel, name),
    '',
    `if [ -f "$LOOP_DIR/${IMPROVE_STOP_FILE}" ]; then`,
    `  echo "VERIFY_CLASS=env plan STOP condition raised by the worker ($LOOP_DIR/${IMPROVE_STOP_FILE}):"`,
    `  cat "$LOOP_DIR/${IMPROVE_STOP_FILE}"`,
    `  echo "A human decides: refresh the plan (/improve reconcile) and re-import, or delete ${IMPROVE_STOP_FILE} and re-run."`,
    '  exit 75',
    'fi',
    '',
    'failed=0',
    'missing_tool=0',
    '',
    '# check <zero|nonzero|empty> <command>',
    'check() {',
    '  local expect="$1" cmd="$2" out status ok=0',
    '  out="$(bash -c "$cmd" 2>&1)"',
    '  status=$?',
    '  case "$expect" in',
    '    zero) [ "$status" -eq 0 ] && ok=1 ;;',
    '    nonzero) [ "$status" -ne 0 ] && [ "$status" -ne 127 ] && ok=1 ;;',
    '    empty) [ -z "$out" ] && [ "$status" -le 1 ] && ok=1 ;;',
    '  esac',
    '  if [ "$ok" -eq 1 ]; then',
    '    echo "PASS  $cmd"',
    '  else',
    '    echo "FAIL  $cmd  (expected $expect, exit $status)"',
    `    printf '%s\\n' "$out" | tail -n 40 | sed 's/^/      /'`,
    '    failed=1',
    '    if [ "$status" -eq 127 ]; then missing_tool=1; fi',
    '  fi',
    '}',
    '',
  ]

  for (const c of checks) {
    const note = c.inferred ? '  # expectation not stated in the plan — assumed exit 0' : ''
    lines.push(`check ${c.expect} ${shq(c.command)}${note}`)
  }

  if (scope) {
    lines.push(
      '',
      '# Scope: only the plan\'s in-scope files may change since the baseline setup.sh recorded.',
      'if [ ! -f "$STATE_DIR/base" ]; then',
      '  echo "VERIFY_CLASS=env no baseline at $STATE_DIR/base — setup.sh records it on the first agent-loop run."',
      '  exit 75',
      'fi',
      'base="$(cat "$STATE_DIR/base")"',
      'scope_bad=0',
      'while IFS= read -r f; do',
      '  [ -n "$f" ] || continue',
      '  if [ -f "$STATE_DIR/preexisting" ] && grep -qxF -- "$f" "$STATE_DIR/preexisting"; then continue; fi',
      '  case "$f" in',
      '    "$LOOP_DIR"/*) continue ;;',
      ...(scope.length > 0 ? [`    ${scope.join('|')}) continue ;;`] : []),
      '  esac',
      '  echo "      out of scope: $f"',
      '  scope_bad=1',
      'done < <( { git diff --name-only "$base"; git ls-files --others --exclude-standard; } | sort -u )',
      'if [ "$scope_bad" -eq 0 ]; then',
      '  echo "PASS  scope: only in-scope files changed since $base"',
      'else',
      '  echo "FAIL  scope: files outside the plan\'s in-scope list changed (revert them or raise a STOP)"',
      '  failed=1',
      'fi',
    )
  }

  const total = checks.length + (scope ? 1 : 0)
  lines.push(
    '',
    'if [ "$failed" -ne 0 ]; then',
    '  if [ "$missing_tool" -eq 1 ]; then echo "VERIFY_CLASS=env a check exited 127 (command not found)"; fi',
    '  exit 1',
    'fi',
    `echo "verify: all ${total} checks passed"`,
    '',
  )
  return lines.join('\n')
}

function renderSetup(
  plan: ImprovePlan,
  name: string,
  opts: BuildImproveBundleOptions,
  install: string | undefined,
): string {
  const lines = [
    '#!/usr/bin/env bash',
    `# Generated by agent-loop-import from ${opts.planRel} (shadcn/improve plan ${plan.number}).`,
    '# Runs before the first worker of each `agent-loop run`. Exit 75 parks the loop (waiting).',
    'set -euo pipefail',
    '',
    ...bashPreamble(opts.loopRel, name),
    'mkdir -p "$STATE_DIR"',
    '',
    '# Baseline for the scope check: HEAD and the already-dirty paths when the loop first ran.',
    'if [ ! -f "$STATE_DIR/base" ]; then',
    '  git rev-parse HEAD > "$STATE_DIR/base"',
    '  { git diff --name-only HEAD; git ls-files --others --exclude-standard; } | sort -u > "$STATE_DIR/preexisting"',
    '  echo "[setup] baseline $(cat "$STATE_DIR/base") recorded in $STATE_DIR (delete it to re-baseline)"',
    'fi',
  ]

  if (plan.plannedAtSha && plan.driftPaths.length > 0) {
    const paths = plan.driftPaths.map(shq).join(' ')
    lines.push(
      '',
      '# Drift check: the plan\'s "Current state" excerpts were written at PLANNED.',
      'BASE="$(cat "$STATE_DIR/base")"',
      `PLANNED=${shq(plan.plannedAtSha)}`,
      'if [ "${AGENT_LOOP_IGNORE_PLAN_DRIFT:-0}" = 1 ]; then',
      '  echo "[setup] plan drift check skipped (AGENT_LOOP_IGNORE_PLAN_DRIFT=1)"',
      'elif ! git cat-file -e "$PLANNED^{commit}" 2>/dev/null; then',
      '  echo "VERIFY_CLASS=env planned-at commit $PLANNED is not in this repo (shallow clone?). Fetch history or set AGENT_LOOP_IGNORE_PLAN_DRIFT=1."',
      '  exit 75',
      `elif ! git diff --quiet "$PLANNED" "$BASE" -- ${paths}; then`,
      '  echo "VERIFY_CLASS=env plan drifted: in-scope files changed since $PLANNED:"',
      `  git diff --stat "$PLANNED" "$BASE" -- ${paths}`,
      '  echo "Refresh the plan (/improve reconcile) and re-import, or set AGENT_LOOP_IGNORE_PLAN_DRIFT=1 after checking the excerpts by hand."',
      '  exit 75',
      'fi',
    )
  }

  if (install) lines.push('', `# Install (from the plan's commands table)`, install)
  lines.push('', 'echo "[setup] ok"', '')
  return lines.join('\n')
}

function renderGoal(
  plan: ImprovePlan,
  opts: BuildImproveBundleOptions,
  b: Omit<ImproveBundle, 'files' | 'name' | 'warnings'>,
): string {
  const stopRel = `${opts.loopRel}/${IMPROVE_STOP_FILE}`
  const scoreboard = [
    `\`verify.sh\` — ${b.checks.length} command check${b.checks.length === 1 ? '' : 's'} from the plan's ${b.checksFrom === 'done-criteria' ? 'Done criteria' : 'step Verify lines'}`,
    b.scopeCheck ? ' + scope check' : '',
  ].join('')
  const status = [
    plan.priority && `priority ${plan.priority}`,
    plan.effort && `effort ${plan.effort}`,
    plan.risk && `risk ${plan.risk}`,
    plan.category && `category ${plan.category}`,
  ]
    .filter(Boolean)
    .join(' · ')

  const lines = [
    `# improve ${plan.number} — ${plan.title}`,
    '',
    `> Imported from \`${opts.planRel}\` (shadcn/improve plan${plan.plannedAtSha ? `, planned at \`${plan.plannedAtSha}\`` : ''}${plan.plannedAtDate ? ` on ${plan.plannedAtDate}` : ''}) by \`agent-loop-import\`.`,
    '> Frozen for this loop. If the plan changes, re-import with `--force` instead of editing this file.',
    ...(status ? ['>', `> ${status}`] : []),
    '',
    '## Finish line (four parts)',
    '',
    '| Part | This loop |',
    '| --- | --- |',
    `| **Outcome** | ${plan.title} |`,
    `| **Scoreboard** | ${scoreboard} |`,
    `| **Permission** | \`maxIterations\` ${b.maxIterations} (effort ${plan.effort ?? 'unstated'}); stagnation stops identical failures |`,
    `| **Budget** | The plan's scope. A STOP condition parks the loop for a human instead of spending more rounds. |`,
    '',
    '## Goal',
    '',
    plan.why || plan.title,
    '',
    'Execute the plan below step by step. Run each step\'s **Verify** command before moving on.',
    '',
    '## Acceptance criteria',
    '',
    '- Success is determined only by the verifier in loop.json (`verify.sh`, exit 0), not by the agent\'s assessment.',
    ...b.checks.map((c) => `- \`${c.command}\` → ${c.expect === 'empty' ? 'no output' : c.expect === 'nonzero' ? 'non-zero exit' : 'exit 0'}`),
    ...(b.scopeCheck ? ['- Only the in-scope files below change (verify.sh scope check).'] : []),
  ]
  if (b.judgeCriteria.length > 0) {
    lines.push(
      '',
      'Checked by the judge (no command in the plan; `reviewGate` is on):',
      '',
      ...b.judgeCriteria.map((c) => `- ${c}`),
    )
  }

  lines.push(
    '',
    '## Constraints',
    '',
    `- Touch only the in-scope files: ${plan.inScope.length > 0 ? plan.inScope.map((p) => `\`${p}\``).join(', ') : '(the plan names none — stay minimal)'}.`,
    '- Do not update `plans/README.md` or the plan file; the harness reports status.',
    '- Do not push or open a PR. Local commits per the plan\'s git workflow are fine.',
    '- Do not edit `GOAL.md`, `verify.sh`, `setup.sh`, or `loop.json` in this loop directory.',
    '',
    '### STOP conditions',
    '',
    `If any of these happens, do not improvise. Write \`${stopRel}\` naming the condition and what you observed, then end your turn. verify.sh parks the loop (exit 75) for a human.`,
    '',
    ...(plan.stopConditions.length > 0
      ? plan.stopConditions.map((s) => `- ${s}`)
      : ['- The code does not match the plan\'s "Current state" excerpts.']),
    '',
    '## Out of scope',
    '',
    ...(plan.outOfScope.length > 0
      ? plan.outOfScope.map((s) => `- ${s}`)
      : ['- Anything not listed as in scope in the plan.']),
    '',
    '## Plan (frozen copy)',
    '',
    demotePlanBody(plan.body),
    '',
  )
  return lines.join('\n')
}

export function buildImproveBundle(plan: ImprovePlan, opts: BuildImproveBundleOptions): ImproveBundle {
  const warnings = [...plan.warnings]
  const name = improveLoopName(plan)

  let checks = dedupeChecks(plan.criteria.flatMap((c) => c.checks))
  let checksFrom: ImproveBundle['checksFrom'] = 'done-criteria'
  if (checks.length === 0 && plan.stepChecks.length > 0) {
    checks = dedupeChecks(plan.stepChecks)
    checksFrom = 'step-verify'
    warnings.push('no runnable Done criteria — verify.sh uses the steps\' Verify commands instead')
  }
  if (checks.length === 0) {
    throw new Error(
      `Plan ${plan.number}: no runnable command in Done criteria or step Verify lines — a verify.sh with no checks would always pass. Tighten the plan (/improve review-plan) first.`,
    )
  }
  const inferred = checks.filter((c) => c.inferred).length
  if (inferred > 0) {
    warnings.push(`${inferred} check(s) had no stated expectation — assumed exit 0 (marked in verify.sh)`)
  }

  const wantsScope = plan.criteria.some((c) => c.scopeCheck) && plan.inScope.length > 0
  const scope = wantsScope ? scopePatterns(plan.inScope, warnings) : undefined
  const judge = judgeCriteria(plan.criteria)
  const reviewGate = judge.length > 0 || /^high/i.test(plan.risk ?? '')
  const maxIterations = effortIterations(plan.effort)

  let install: string | undefined
  if (plan.installCommand) {
    if (SAFE_INSTALL.test(plan.installCommand)) install = plan.installCommand
    else warnings.push(`install command \`${plan.installCommand}\` left out of setup.sh — add it by hand if needed`)
  }

  const driftCheck = Boolean(plan.plannedAtSha && plan.driftPaths.length > 0)
  const meta = {
    checks,
    checksFrom,
    scopeCheck: Boolean(scope),
    driftCheck,
    judgeCriteria: judge,
    reviewGate,
    maxIterations,
  }

  const loopJson: Record<string, unknown> = {
    verify: `bash ${opts.loopRel}/verify.sh`,
    setup: `bash ${opts.loopRel}/setup.sh`,
    maxIterations,
  }
  if (reviewGate) {
    loopJson.postQualityReview = true
    loopJson.reviewGate = true
  }

  return {
    name,
    ...meta,
    warnings,
    files: {
      'GOAL.md': renderGoal(plan, opts, meta),
      'verify.sh': renderVerify(plan, name, opts, checks, scope),
      'setup.sh': renderSetup(plan, name, opts, install),
      'loop.json': `${JSON.stringify(loopJson, null, 2)}\n`,
    },
  }
}

export type BatchOrder = {
  ordered: ImprovePlan[]
  skipped: { number: string; reason: string }[]
}

const SKIP_STATUSES = new Set(['DONE', 'REJECTED', 'BLOCKED'])

/**
 * Order plans for `agent-loop-batch`: index order (else plan number), dependencies first.
 * Skips DONE / REJECTED / BLOCKED rows, and plans whose dependencies are neither
 * DONE nor part of this batch.
 */
export function orderPlansForBatch(plans: ImprovePlan[], index: PlanIndexRow[]): BatchOrder {
  const statusOf = new Map(index.map((r) => [r.number, r.status]))
  const indexDeps = new Map(index.map((r) => [r.number, r.dependsOn]))
  const position = new Map(index.map((r, i) => [r.number, i]))
  const skipped: BatchOrder['skipped'] = []

  let candidates = plans.filter((p) => {
    const status = statusOf.get(p.number)
    if (status && SKIP_STATUSES.has(status)) {
      skipped.push({ number: p.number, reason: `status ${status} in plans/README.md` })
      return false
    }
    return true
  })

  const deps = (p: ImprovePlan) => [...new Set([...p.dependsOn, ...(indexDeps.get(p.number) ?? [])])]

  // Drop plans whose dependencies cannot be satisfied (transitively).
  for (let changed = true; changed; ) {
    changed = false
    const inBatch = new Set(candidates.map((p) => p.number))
    candidates = candidates.filter((p) => {
      const unmet = deps(p).filter((d) => !inBatch.has(d) && statusOf.get(d) !== 'DONE')
      if (unmet.length === 0) return true
      skipped.push({ number: p.number, reason: `depends on ${unmet.join(', ')} (not DONE, not in this batch)` })
      changed = true
      return false
    })
  }

  const rank = (p: ImprovePlan) => position.get(p.number) ?? 10_000 + Number(p.number)
  const pending = [...candidates].sort((a, b) => rank(a) - rank(b))
  const ordered: ImprovePlan[] = []
  const placed = new Set<string>()
  const inBatch = new Set(pending.map((p) => p.number))
  while (pending.length > 0) {
    const i = pending.findIndex((p) => deps(p).every((d) => !inBatch.has(d) || placed.has(d)))
    if (i === -1) {
      for (const p of pending) skipped.push({ number: p.number, reason: 'dependency cycle' })
      break
    }
    const [next] = pending.splice(i, 1)
    ordered.push(next)
    placed.add(next.number)
  }
  return { ordered, skipped }
}

export function renderImproveBatch(bundles: Pick<ImproveBundle, 'name'>[], plans: ImprovePlan[]): string {
  const loops = bundles.map((b, i) => {
    const focus = plans[i]?.reviewerFocus.join(' ').trim()
    return focus ? { path: b.name, rubric: focus } : b.name
  })
  return `${JSON.stringify({ loops, syncOnSuccess: false }, null, 2)}\n`
}
